namespace CuMusicClub.Domain.Enums;

/// <summary>
/// Результат попытки угадать логин Яндекса по отображаемому имени пользователя.
/// </summary>
public enum YandexLoginGuessStatus
{
    Found = 1,      // Нашли однозначный контакт, логин записан пользователю
    NotFound = 2,   // Контакт не найден или найдено несколько — выбрать нельзя
    Conflict = 3,   // Найденный логин уже занят другим пользователем
    Error = 4       // Яндекс не ответил / протухли cookies — попытка повторится при следующем запуске
}
